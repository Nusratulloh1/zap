// Подписи записей истории и кэшбэка.
//
// Часть из них сервер раньше писал по-русски прямо в базу, и они показывались
// так независимо от языка интерфейса. Теперь вместе с текстом приходит ключ
// перевода — но только для служебных строк. Название заведения или своя
// заметка ключа не имеют и показываются как есть, что для них и правильно.
import { hasKey, translate } from '@/i18n';

export function entryText(text: string, key?: string): string {
  if (key && hasKey(key)) return translate(key);
  return text;
}
