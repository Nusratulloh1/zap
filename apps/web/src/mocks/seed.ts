import type { Db } from '@zap/shared/types'

const DAY = 86400000

/** n days ago at the given time of day */
function daysAgo(n: number, h = 12, m = 0): number {
  const d = new Date()
  d.setHours(h, m, 0, 0)
  return d.getTime() - n * DAY
}

/** most recent past Friday */
function lastFriday(): number {
  const d = new Date()
  const diff = (d.getDay() - 5 + 7) % 7 || 7
  return daysAgo(diff, 19, 30)
}

