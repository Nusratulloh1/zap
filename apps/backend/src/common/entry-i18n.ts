// Ключи перевода для служебных подписей в истории и кэшбэке.
//
// Раньше эти строки писались в базу по-русски и уезжали на экран как есть —
// независимо от языка интерфейса. Теперь клиенту отдаётся ключ, а сам текст
// он берёт из своих локалей.
//
// Таблица работает и на новые записи, и на старые: ключ выводится из уже
// сохранённого текста, поэтому ни миграции, ни переписывания данных не нужно.
// Если текст незнакомый (название заведения, произвольная заметка) — ключа нет
// и клиент показывает строку как есть, что для таких случаев и правильно.
const BY_TEXT: Record<string, string> = {
  Оплата: 'entry.payment',
  'Оплата целиком': 'entry.paidWhole',
  'Долг погашен': 'entry.debtSettled',
  'Потрачено на сплит': 'entry.spentOnSplit',
  'Ваша доля в сплите': 'entry.yourShare',
  'Покрыли остаток сплита': 'entry.coveredRest',
  'Групповой кэшбэк': 'entry.groupCashback',
  'Вывод на карту': 'entry.withdrawToCard',
  'Вывод кэшбэка': 'entry.cashbackWithdrawal',
}

export function entryKey(text: string | null | undefined): string | undefined {
  if (!text) return undefined
  return BY_TEXT[text.trim()]
}
